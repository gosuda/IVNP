func requireNextKeyHeaders(t testing.TB, payload []byte, want ...[3]byte) {
	t.Helper()
	var got [][3]byte
	for len(payload) >= 3 {
		kind, size := payload[0], int(binary.BigEndian.Uint16(payload[1:3]))
		payload = payload[3:]
		if size > len(payload) {
			t.Fatal("truncated authenticated payload")
		}
		if kind == ratchetNextKey {
			if size != 3 && size != 35 {
				t.Fatalf("NextKey size = %d", size)
			}
			got = append(got, [3]byte(payload[:3]))
		}
		payload = payload[size:]
	}
	if len(got) != len(want) {
		t.Fatalf("NextKey headers = %x, want %x", got, want)
	}
	for index := range want {
		if got[index] != want[index] {
			t.Fatalf("NextKey headers = %x, want %x", got, want)
		}
	}
}

