func TestReplyTagSetKDFMatchesJavaI2P2130Vector(t *testing.T) {
	// Generated by RatchetTagSet from the I2P 2.13.0 release router.jar
	// using i2p.jar SHA-256 1a6f9296fcd07854dffce9c11850c2ebe75a2269aab39e2be869168c0ebc6ef7.
	const javaData = "0665ff1f1ebfe25e4facf84840b0428296e73662ff3b77edfe4904bf7063e3fa"
	const javaNextRoot = "f764b2c8a236502964fde33cd9d81aaf882ba2403f59c916a3e244d9ffb0f6a7"
	javaEntries := []struct {
		tag string
		key string
	}{
		{"2698fd64096e9f0d", "59e67dac8fe352e2956bd84f911efc7b6f1933c05da05360554c88614978ca66"},
		{"8eb1f7070dc0e53d", "f822968404d098d2030a6b93eab2a6ca9c6eac4853a471bc60b82b43011232ae"},
		{"60c4eaee68a6ede1", "e3e860ecd0f17cc31e2b86bfe45320980e8ca183aaaf18b4050584c65697d8a0"},
	}
	var chain [32]byte
	for i := range chain {
		chain[i] = byte(i + 1)
	}
	data := hkdf64(chain[:], nil, "SessionReplyTags")
	if got := hex.EncodeToString(data[:32]); got != javaData {
		t.Fatalf("SessionReplyTags KDF = %s, want Java I2P 2.13.0 %s", got, javaData)
	}
	set, err := newTagSet(0, chain, data[:32], 1)
	if err != nil {
		t.Fatal(err)
	}
	if got := hex.EncodeToString(set.nextRoot[:]); got != javaNextRoot {
		t.Fatalf("next root = %s, want Java I2P 2.13.0 %s", got, javaNextRoot)
	}
	reply := deriveReplyTag(chain)
	if got := hex.EncodeToString(reply[:]); got != javaEntries[0].tag {
		t.Fatalf("reply tag = %s, want Java I2P 2.13.0 %s", got, javaEntries[0].tag)
	}
	for index, want := range javaEntries {
		entry, nextErr := set.nextEntry()
		if nextErr != nil {
			t.Fatal(nextErr)
		}
		if got := hex.EncodeToString(entry.tag[:]); got != want.tag {
			t.Fatalf("tag %d = %s, want Java I2P 2.13.0 %s", index, got, want.tag)
		}
		if got := hex.EncodeToString(entry.key[:]); got != want.key {
			t.Fatalf("key %d = %s, want Java I2P 2.13.0 %s", index, got, want.key)
		}
	}
}

func TestRatchetDHStepMatchesJavaI2P2130Vector(t *testing.T) {
	// Generated by the official I2P 2.13.0 RatchetTagSet and HKDF classes.
	var root, data, shared [32]byte
	for index := range root {
		root[index] = byte(index + 0x01)
		data[index] = byte(index + 0x21)
		shared[index] = byte(index + 0x41)
	}
	initial, err := newTagSet(0, root, data[:], 0)
	if err != nil {
		t.Fatal(err)
	}
	defer releaseTagSet(initial)
	manager := &RatchetManager{config: RatchetConfig{SessionLifetime: defaultSessionLife}}
	next, _, err := manager.prepareRatchetDirectionLocked(&session{outbound: initial}, true, shared[:], 0)
	if err != nil {
		t.Fatal(err)
	}
	defer releaseTagSet(next)
	if got := hex.EncodeToString(next.nextRoot[:]); got != "5b9f9d2d46bec1d6dfd55be052a4f00291a547541c850c83ea1e14ac2db745fd" {
		t.Fatalf("post-DH root differs from Java I2P: %s", got)
	}
	want := []struct{ tag, key string }{
		{"2569ae803872b0fb", "28198055cf8bb04edc906c4bed05d832ca5b96ee5bdf9f71aa5d6a3e9e66697b"},
		{"58212a3e735e815e", "11c9f9fa7997a03766199a65b2b539d6fbbf1936332311c53939da96c36f1a1d"},
		{"1278007fe4f02336", "8ec9804f4320cb4e243f20d463145556424b11af4f69c034b5518e5a85088e7a"},
	}
	for index, entry := range want {
		got, err := next.nextEntry()
		if err != nil {
			t.Fatal(err)
		}
		if hex.EncodeToString(got.tag[:]) != entry.tag || hex.EncodeToString(got.key[:]) != entry.key {
			t.Fatalf("post-DH entry %d differs from Java I2P: tag=%x key=%x", index, got.tag, got.key)
		}
		clear(got.key[:])
	}
}

func TestRatchetExistingSessionUsesNoiseLittleEndianNonce(t *testing.T) {
	a, b, aPeer, bPeer, now := ratchetPair(t)
	defer a.ReleaseSensitive()
	defer b.ReleaseSensitive()
	establishRatchet(t, a, b, aPeer, bPeer, now)
	first, err := a.EncryptExisting(make([]byte, 256), bPeer, clove("first"), RatchetOptions{}, now+1)
	if err != nil {
		t.Fatal(err)
	}
	if _, err = b.Receive(make([]byte, 256), nil, first, now+1); err != nil {
		t.Fatal(err)
	}
	second, err := a.EncryptExisting(make([]byte, 256), bPeer, clove("second"), RatchetOptions{}, now+2)
	if err != nil {
		t.Fatal(err)
	}
	var tag [ratchetTagLen]byte
	copy(tag[:], second)
	entry, ok := b.inbound[tag]
	if !ok || entry.n == 0 {
		t.Fatalf("second message tag entry = %#v, found %t", entry, ok)
	}
	var nonce [cryptography.ChaChaNonceSize]byte
	binary.LittleEndian.PutUint64(nonce[4:], uint64(entry.n))
	plain := make([]byte, len(second)-ratchetTagLen-cryptography.ChaChaTagSize)
	if _, err = cryptography.OpenChaCha20Poly1305To(plain, entry.key[:], nonce[:], second[ratchetTagLen:], second[:ratchetTagLen]); err != nil {
		t.Fatal(err)
	}
}

func TestRatchetProductionEncryptAutomaticallyAdvancesDH(t *testing.T) {
	a, b, aPeer, bPeer, now := ratchetPair(t)
	defer a.ReleaseSensitive()
	defer b.ReleaseSensitive()
	bInboundPeer := establishRatchet(t, a, b, aPeer, bPeer, now)
	public := ratchetPublic(t, b)
	var encrypted, received [256]byte
	for index := uint64(1); index <= automaticDHRatchetMessages; index++ {
		packet, err := a.Encrypt(encrypted[:], bPeer, public, 4, nil, now+index)
		if err != nil {
			t.Fatal(err)
		}
		if _, err = b.Receive(received[:], nil, packet, now+index); err != nil {
			t.Fatal(err)
		}
	}
	forward, err := a.Encrypt(encrypted[:], bPeer, public, 4, clove("forward"), now+automaticDHRatchetMessages+1)
	if err != nil {
		t.Fatal(err)
	}
	result, err := b.Receive(received[:], nil, forward, now+automaticDHRatchetMessages+1)
	if err != nil || !result.DHStep {
		t.Fatalf("automatic forward DH = %#v, %v", result, err)
	}
	repeated, err := a.Encrypt(encrypted[:], bPeer, public, 4, clove("repeated"), now+automaticDHRatchetMessages+2)
	if err != nil {
		t.Fatal(err)
	}
	if result, err = b.Receive(received[:], nil, repeated, now+automaticDHRatchetMessages+2); err != nil || !result.DHStep {
		t.Fatalf("idempotent pending DH = %#v, %v", result, err)
	}
	reverse, err := b.Encrypt(encrypted[:], bInboundPeer, ratchetPublic(t, a), 4, clove("reverse"), now+automaticDHRatchetMessages+3)
	if err != nil {
		t.Fatal(err)
	}
	if result, err = a.Receive(received[:], nil, reverse, now+automaticDHRatchetMessages+3); err != nil || !result.DHStep {
		t.Fatalf("automatic reverse DH = %#v, %v", result, err)
	}
}

